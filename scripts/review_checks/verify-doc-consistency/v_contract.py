print(f"  shaped-skeleton fit returns betas={fs.betas}")
print(f"  shaped: reconstruct vs input {np.nanmax(np.linalg.norm(ours-L,axis=1)):.2e} m; SMPL-X fwd(returned betas) vs reconstruct max {max(np.linalg.norm(Jr[s]-ours[m]) for s,m in ARM_CORRESPONDENCE)*1000:.1f} mm; with true betas {max(np.linalg.norm(Jt[s]-ours[m]) for s,m in ARM_CORRESPONDENCE)*1000:.4f} mm")

