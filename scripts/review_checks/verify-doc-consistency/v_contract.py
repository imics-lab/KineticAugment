"""Independent verifier checks for the doc-consistency cluster (contract, rotation, betas,
unobserved outputs, direction error, constrained-joint count, coverage, image input)."""
import glob
import warnings
import numpy as np
import torch
from scipy.spatial.transform import Rotation as R

from kinetic_augment.body_model.converter import fit_body, reconstruct_body, ARM_CORRESPONDENCE, BodyFit
from kinetic_augment.body_model.kinematics import forward_kinematics
from kinetic_augment.body_model.skeleton import SMPLXSkeleton
from kinetic_augment.body_model.swing_ik import SMPLX_ARM_BONES, solve_swing_ik
from kinetic_augment.body_model.alignment import similarity_transform, apply_similarity

sk = SMPLXSkeleton(model_path="models")
ARM_J = [16, 18, 17, 19]
NAMES = {16: "L shoulder", 18: "L elbow", 17: "R shoulder", 19: "R elbow"}

def lm_from(skel, rots):
    j = forward_kinematics(rots, skel)
    L = np.full((33, 3), np.nan)
    for s, m in ARM_CORRESPONDENCE:
        L[m] = j[s]
    return L, np.isfinite(L).all(1)

# ---------- F5d: position vs rotation recovery (my own seed + generator) ----------
print("== F5d rotation recovery ==")
rng = np.random.default_rng(2026)
pos_worst = 0.0
rot_err = {j: [] for j in ARM_J}
for _ in range(300):
    truth = np.zeros((55, 3))
    for j in ARM_J:
        truth[j] = rng.normal(0, 0.4, 3)
    L, v = lm_from(sk, truth)
    fit = fit_body(L, v, sk)
    out = reconstruct_body(fit, sk)
    pos_worst = max(pos_worst, np.nanmax(np.linalg.norm(out - L, axis=1)))
    bp = fit.body_pose.reshape(21, 3)
    for j in ARM_J:
        e = (R.from_rotvec(bp[j - 1]).inv() * R.from_rotvec(truth[j])).magnitude()
        rot_err[j].append(np.degrees(e))
print(f"300 poses N(0,0.4) seed 2026: worst position err {pos_worst:.3e} m")
for j in ARM_J:
    a = np.array(rot_err[j])
    print(f"  {NAMES[j]}: local-rot err median {np.median(a):.1f} deg, p95 {np.percentile(a,95):.1f}, max {a.max():.1f}")
# global_orient recovered?
# pure-swing family: truth generated by the IK itself -> should be exactly recovered
rng = np.random.default_rng(7)
worst_sw = 0.0
for _ in range(100):
    t0 = np.zeros((55, 3))
    for j in ARM_J:
        t0[j] = rng.normal(0, 0.4, 3)
    L0, _ = lm_from(sk, t0)
    swing_truth = solve_swing_ik(L0, sk, SMPLX_ARM_BONES)  # zero-twist representative
    L, v = lm_from(sk, swing_truth)
    bp = fit_body(L, v, sk).body_pose.reshape(21, 3)
    for j in ARM_J:
        worst_sw = max(worst_sw, np.degrees((R.from_rotvec(bp[j-1]).inv() * R.from_rotvec(swing_truth[j])).magnitude()))
print(f"  zero-twist truth family: worst local-rot err {worst_sw:.2e} deg")

# ---------- F5-contract: SMPL-X forward vs reconstruct_body on real frames ----------
print("== F5-contract: real SMPL-X forward vs reconstruct_body (all real frames) ==")
import smplx
model_default = smplx.create(model_path="models", model_type="smplx", gender="neutral", use_pca=False, batch_size=1)  # default flat_hand_mean=False, independent instance
def t(a):
    return torch.tensor(np.asarray(a), dtype=torch.float32)[None]

worst_fw = 0.0
n_frames = 0
n_fit = 0
joint_counts = {}
unobs = []
dir_err = {b: [] for b in range(4)}
invalid_wrist_instances = 0
img_input = None
fits_real = []
for path in sorted(glob.glob("data/test_output/*_world.npz")):
    d = np.load(path)
    P = d["landmarks"].astype(np.float64)
    V = d["visibility"]
    ok_all = np.isfinite(P).all(-1) & (V >= 0.5)
    both = ok_all[:, 11] & ok_all[:, 12]
    width = float(np.median(np.linalg.norm(P[both, 11] - P[both, 12], axis=-1)))
    for f in range(len(P)):
        n_frames += 1
        ok = ok_all[f]
        try:
            fit = fit_body(P[f], ok, sk)
        except ValueError:
            continue
        n_fit += 1
        out = reconstruct_body(fit, sk)
        with torch.no_grad():
            J = model_default(body_pose=t(fit.body_pose), global_orient=t(fit.global_orient),
                              transl=t(fit.transl), betas=t(fit.betas), return_verts=False).joints[0].numpy()
        for s, m in ARM_CORRESPONDENCE:
            worst_fw = max(worst_fw, np.linalg.norm(out[m] - J[s]))
        nz = int((np.abs(fit.body_pose.reshape(21, 3)).sum(1) > 0).sum())
        joint_counts[nz] = joint_counts.get(nz, 0) + 1
        # unobserved but modelled: wrists (and elbows) flagged invalid while finite in output
        for m in (13, 14, 15, 16):
            if not ok[m] and np.isfinite(out[m]).all():
                invalid_wrist_instances += 1 if m in (15, 16) else 0
                if m in (15, 16) and np.isfinite(P[f, m]).all():
                    unobs.append(np.linalg.norm(out[m] - P[f, m]) / width)
        for b, (a_, c_) in enumerate([(11, 13), (13, 15), (12, 14), (14, 16)]):
            if ok[a_] and ok[c_]:
                u = out[c_] - out[a_]; w = P[f, c_] - P[f, a_]
                dir_err[b].append(np.degrees(np.arccos(np.clip(u @ w / np.linalg.norm(u) / np.linalg.norm(w), -1, 1))))
        fits_real.append((fit, P[f], ok))
print(f"frames {n_frames}, fitted {n_fit}; worst |SMPL-X fwd (flat_hand_mean=False instance) - reconstruct_body| = {worst_fw:.3e} m")
print(f"nonzero body_pose joints per frame: {dict(sorted(joint_counts.items()))}")
print(f"invalid-wrist instances emitted finite: {invalid_wrist_instances}; dist to MP's own estimate (% SW): median {np.median(unobs)*100:.1f}, p95 {np.percentile(unobs,95)*100:.1f}, n={len(unobs)}")
for b, nm in enumerate(["L upper", "L fore", "R upper", "R fore"]):
    a = np.array(dir_err[b])
    print(f"  direct-output direction err {nm}: median {np.median(a):.2f} deg, p95 {np.percentile(a,95):.2f}")
go = [np.degrees(np.linalg.norm(fr[0].global_orient)) for fr in fits_real]
print(f"  median |global_orient| {np.median(go):.1f} deg")

