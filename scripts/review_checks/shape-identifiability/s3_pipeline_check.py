"""Q3 via the repo's own code + the real smplx forward pass.

Landmarks are generated by the REAL SMPL-X forward (smplx package) for body A,
then fitted by converter.fit_body with a skeleton of body B (different height /
volume, same 5 lengths). If the converter's reconstruction is equally exact for
B, the observation model cannot tell A from B.
"""
import os, sys
import numpy as np, torch, smplx
from common import SNAP, body_stats
os.chdir(SNAP)
from kinetic_augment.body_model.skeleton import SMPLXSkeleton
from kinetic_augment.body_model.converter import fit_body, reconstruct_body, ARM_CORRESPONDENCE
from kinetic_augment.body_model.swing_ik import SMPLX_ARM_BONES

hi, lo = np.load(sys.argv[1] if len(sys.argv) > 1 else
                 "scripts/review_checks/shape-identifiability/pair_height_tmpl.npy")
bodies = {"A=height MAX": hi, "B=height MIN": lo, "C=betas 0": np.zeros(10),
          "D=+1 sigma beta0": np.eye(10)[0]}
model = smplx.create("models", model_type="smplx", gender="neutral", use_pca=False,
                     flat_hand_mean=True, num_betas=10, batch_size=1)

def real_landmarks(beta, rot):
    with torch.no_grad():
        out = model(betas=torch.tensor(beta[None], dtype=torch.float32),
                    global_orient=torch.tensor(rot[0][None], dtype=torch.float32),
                    body_pose=torch.tensor(rot[1:22].reshape(1, 63), dtype=torch.float32))
    J = out.joints[0, :55].numpy().astype(np.float64)
    lm = np.full((33, 3), np.nan)
    for s, m in ARM_CORRESPONDENCE:
        lm[m] = J[s]
    return lm

skel = {k: SMPLXSkeleton(model_path="models", betas=b) for k, b in bodies.items()}
for k, b in bodies.items():
    st = body_stats(b)
    print(f"{k:<18} height {st['height_m']*100:6.1f} cm  leg {st['L_leg_m']*100:5.1f} cm  vol {st['volume_L']:5.1f} L")

rng = np.random.default_rng(7)
poses = []
for _ in range(100):
    r = np.zeros((55, 3))
    for joint, *_ in SMPLX_ARM_BONES:
        r[joint] = rng.normal(0, 0.5, 3)
    poses.append(r)

print("\nTruth generated by real SMPL-X forward with body A, root unrotated, 100 random arm poses.")
print("Error of fit_body -> reconstruct_body using each candidate skeleton (mm):")
for k, sk in skel.items():
    errs = []
    for r in poses:
        lm = real_landmarks(bodies["A=height MAX"], r)
        ok = np.isfinite(lm).all(1)
        out = reconstruct_body(fit_body(lm, ok, sk), sk)
        errs.append(np.linalg.norm(out[ok] - lm[ok], axis=1))
    e = np.concatenate(errs) * 1000
    print(f"  fit with {k:<18} median {np.median(e):8.4f}  max {e.max():8.4f}")
