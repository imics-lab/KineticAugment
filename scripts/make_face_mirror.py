"""
Generate `src/kinetic_augment/augmentations/face_mirror.py`, the 478-point face mirror table.

`FACE_MIRROR[i]` is the MediaPipe face landmark that takes point i's place when the face is
reflected left/right. The 468 mesh points come from the canonical face model
(`models/mediapipe/canonical_face_model.obj`): reflect x, then a Hungarian assignment
(`scipy.optimize.linear_sum_assignment`) of reflected points to points, so the map is a
permutation. Mutual pairs are kept and the few leftovers are paired by smallest symmetrised
distance, which makes the permutation an involution. Midline points map to themselves.

The ten iris points (468-477) are not in the canonical model. MediaPipe orders each iris as
centre, +x, top, -x, bottom (image axes; checked on pilot clip 01991: both irises have the same
order), so a reflection maps 468<->473, 469<->476, 470<->475, 471<->474 and 472<->477.

Usage: python scripts/make_face_mirror.py [--obj PATH] [--out PATH]
"""

import argparse
from pathlib import Path

import numpy as np
from scipy.optimize import linear_sum_assignment

REPO = Path(__file__).resolve().parents[1]
DEFAULT_OBJ = REPO / "models" / "mediapipe" / "canonical_face_model.obj"
DEFAULT_OUT = REPO / "src" / "kinetic_augment" / "augmentations" / "face_mirror.py"
MESH_POINTS = 468
IRIS_PAIRS = ((468, 473), (469, 476), (470, 475), (471, 474), (472, 477))


def load_vertices(path: Path) -> np.ndarray:
    rows = [line.split()[1:4] for line in Path(path).read_text().splitlines() if line[:2] == "v "]
    vertices = np.array(rows, dtype=np.float64)
    if len(vertices) != MESH_POINTS:
        raise ValueError(f"expected {MESH_POINTS} vertices, found {len(vertices)}")
    return vertices


def mesh_mirror(vertices: np.ndarray) -> np.ndarray:
    """Involutive permutation of the mesh points from reflect-x nearest assignment."""
    reflected = vertices * np.array([-1.0, 1.0, 1.0])
    cost = np.linalg.norm(reflected[:, None, :] - vertices[None, :, :], axis=-1)
    _, assigned = linear_sum_assignment(cost)
    perm = np.full(len(vertices), -1, dtype=int)
    for i, j in enumerate(assigned):
        if assigned[j] == i:
            perm[i] = j
    left = [i for i in range(len(vertices)) if perm[i] < 0]
    sym = (cost + cost.T) / 2.0
    candidates = sorted(
        (sym[i, j], i, j) for a, i in enumerate(left) for j in left[a:]
    )  # includes i == j
    for _, i, j in candidates:
        if perm[i] < 0 and perm[j] < 0:
            perm[i], perm[j] = j, i
    return perm


def face_mirror(vertices: np.ndarray) -> np.ndarray:
    perm = np.arange(MESH_POINTS + 10)
    perm[:MESH_POINTS] = mesh_mirror(vertices)
    for a, b in IRIS_PAIRS:
        perm[a], perm[b] = b, a
    return perm


def render(perm: np.ndarray) -> str:
    lines = []
    for start in range(0, len(perm), 12):
        lines.append("    " + ", ".join(str(int(v)) for v in perm[start : start + 12]) + ",")
    body = "\n".join(lines)
    return (
        '"""\n'
        "The 478-point MediaPipe face mirror table.\n\n"
        "GENERATED by scripts/make_face_mirror.py from models/mediapipe/canonical_face_model.obj;\n"
        "do not edit by hand. `FACE_MIRROR[i]` is the landmark that takes point i's place when the\n"
        "face is reflected left/right (an involution). Iris points pair 468-472 with 473-477.\n"
        '"""\n\n'
        "from typing import Tuple\n\n"
        "# fmt: off\n"
        f"FACE_MIRROR: Tuple[int, ...] = (\n{body}\n)\n"
        "# fmt: on\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("--obj", type=Path, default=DEFAULT_OBJ)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    perm = face_mirror(load_vertices(args.obj))
    assert sorted(perm) == list(range(len(perm))) and (perm[perm] == np.arange(len(perm))).all()
    args.out.write_text(render(perm))
    moved = int((perm != np.arange(len(perm))).sum())
    print(f"wrote {args.out} ({len(perm)} points, {moved} moved)")


if __name__ == "__main__":
    main()
